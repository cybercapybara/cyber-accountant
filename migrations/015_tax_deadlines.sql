-- Календарь налоговых дедлайнов (спека §7.1 / Task 6, фаза P2). СИСТЕМНЫЙ,
-- без org_id — ТРЕТЬЕ документированное исключение из правила org-скоупа
-- (первое — accounts, migrations/008_accounts.sql; второе — tax_rates /
-- tax_constants, migrations/011_tax_reference.sql): сроки сдачи и уплаты по
-- НК РК одинаковы для всех тенантов, поэтому нет ни одной строки, которая
-- имела бы смысл "принадлежать" одной org. Правила здесь описывают, КОГДА
-- наступает срок по конкретной форме (form/kind/period_kind/due_day/
-- due_month_offset) — конкретные календарные даты для конкретного
-- пользователя разворачивает Tax::TaxCalendar::upcoming() в
-- src/tax/TaxCalendar.hpp, включая перенос выходного дня на следующий
-- рабочий (см. Doxygen там же про известное ограничение: праздники РК не
-- учитываются в P2).
--
-- due_month_offset — сколько МЕСЯЦЕВ после окончания отчётного периода
-- наступает срок (например, полугодие заканчивается 30 июня, due_month_offset=2
-- => срок приходится на август); due_day — число этого месяца.
--
-- Seed сверен построчно с первоисточниками по состоянию на 2026-08-14:
--  * adilet.zan.kz/rus/docs/K2500000214 — Кодекс РК "О налогах и других
--    обязательных платежах в бюджет" (Налоговый кодекс) от 18.07.2025 №214-VIII,
--    в силе с 01.01.2026 — те же первоисточник и редакция, что уже сверены
--    в migrations/011_tax_reference.sql (см. там список статей по ставкам);
--  * kgd.gov.kz — раздел "ФНО на 2026 год" / налоговый календарь Комитета
--    государственных доходов (подтверждает конкретные календарные даты
--    2026 года, например "форму 910.00 за I полугодие сдать до 15/17 августа");
--  * вторичные источники для перекрёстной проверки: pro1c.kz, mybuh.kz,
--    bes.media, balanc.kz, blog.trustme.kz, 1cbit.kz, kodeksy-kz.com
--    (постатейное зеркало текста кодекса).
--
-- РАЗРЕШЁННОЕ противоречие (см. также отчёт задачи):
--  1) Периодичность формы 910.00 — вторичные источники расходились между
--     "ежемесячно" и "полугодие". Разрешено в пользу ПОЛУГОДИЯ: ст.722 НК РК
--     прямо называет налоговым/отчётным периодом для СНР на основе
--     упрощённой декларации именно полугодие (это же ст.722 уже цитируется
--     в migrations/011_tax_reference.sql для ставки snr_simplified). Версия
--     "ежемесячно" относится к другим обязательствам этого же
--     налогоплательщика (например, помесячному учёту доходов для контроля
--     лимита или к авансовым/иным платежам), а не к периодичности самой
--     декларации 910.00 — подставлять её в этот справочник было бы ошибкой.
--     Сроки самой декларации и уплаты — ст.727 НК РК: п.1 — декларация не
--     позднее 15 числа ВТОРОГО месяца, следующего за отчётным полугодием;
--     п.2 — уплата не позднее 25 числа ВТОРОГО месяца, следующего за
--     отчётным полугодием. Для I полугодия 2026 (янв-июнь) это 15 и
--     25 августа 2026 — подтверждено kgd.gov.kz, bes.media, pro1c.kz.
--  2) Форма 300.00 (НДС) — отчётный период КВАРТАЛ (ст.504 НК РК), но срок
--     сдачи и срок уплаты — РАЗНЫЕ ЧИСЛА ОДНОГО И ТОГО ЖЕ (второго) месяца
--     после квартала, а не "первый месяц для сдачи / второй для уплаты", как
--     можно ошибочно предположить: ст.505 НК РК — декларация представляется
--     не ранее 15 числа месяца, следующего за кварталом, и НЕ ПОЗДНЕЕ 15
--     числа ВТОРОГО месяца, следующего за кварталом; ст.506 НК РК — НДС
--     уплачивается не позднее 25 числа ТОГО ЖЕ второго месяца. Оба срока
--     (15-е и 25-е) относятся к одному и тому же "втором месяцу после
--     квартала" — подтверждено blog.trustme.kz ("единый день
--     налогоплательщика" вокруг 25 числа), 1cbit.kz, pro1c.kz.
--
-- Форма 200.00 (декларация по ИПН/социальным платежам за работников,
-- ежеквартальная) — CHECK допускает её как задел на будущее, но seed НЕ
-- добавлен: обязательность этой формы зависит от профиля клиента (наличие
-- наёмных работников на ОУР), что ещё не подтверждено для нашего профиля;
-- когда подтвердится — добавляется новой строкой миграции, без изменения
-- этой (как и form не расширяется задним числом).
CREATE TABLE IF NOT EXISTS tax_deadlines (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    form              TEXT NOT NULL CHECK (form IN ('910.00','300.00','200.00')),
    kind              TEXT NOT NULL CHECK (kind IN ('report','payment')),
    period_kind       TEXT NOT NULL CHECK (period_kind IN ('month','quarter','half_year','year')),
    due_day           INTEGER NOT NULL CHECK (due_day BETWEEN 1 AND 28),
    due_month_offset  INTEGER NOT NULL CHECK (due_month_offset BETWEEN 0 AND 11),
    effective_from    DATE NOT NULL,
    source_note       TEXT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (form, kind, effective_from)
);
CREATE INDEX IF NOT EXISTS idx_tax_deadlines_lookup ON tax_deadlines (form, kind, effective_from DESC);

