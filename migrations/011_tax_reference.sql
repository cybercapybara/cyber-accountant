--  * вторичные источники для перекрёстной проверки: mybuh.kz, pro1c.kz,
--    uchet.kz, kgd.gov.kz (пресс-служба ДГД).
--
-- Разрешённые в ходе сверки расхождения с черновиком (см. также отчёт задачи):
--  1) НДС порог регистрации — НЕ фиксированные "40 млн ₸", а 10 000 МРП
--     (НК РК ст.99 п.4 пп.2, срок постановки на учёт — ст.101 п.3); на 2026 год
--     это 10 000 × 4325 = 43 250 000 ₸ (было ошибочно указано 40 000 000 ₸).
--  2) Предел базы ОПВ — подтверждён как 50 МЗП (Соцкодекс ст.249), а не
--     "коридор 1-7 МЗП": этот коридор относится к СО (ст.245), не к ОПВ —
--     противоречие было следствием смешения двух разных платежей источниками.
--  3) Взаимозачёт социального налога и социальных отчислений с 2026 года
--     отменён (НК РК, новая редакция — исчисленный соцналог более НЕ
--     уменьшается на сумму СО); соцналог также не уплачивается при СНР на
--     основе упрощённой декларации (см. source_note строки social_tax).
CREATE TABLE IF NOT EXISTS tax_rates (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    kind           TEXT NOT NULL CHECK (kind IN
                     ('vat','snr_simplified','ipn','opv','opvr','so','osms','vosms','social_tax')),
    rate_bp        INTEGER NOT NULL CHECK (rate_bp >= 0 AND rate_bp <= 10000),
    region         TEXT,
    effective_from DATE NOT NULL,
    effective_to   DATE,
    source_note    TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX IF NOT EXISTS idx_tax_rates_lookup ON tax_rates (kind, effective_from DESC);

CREATE TABLE IF NOT EXISTS tax_constants (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    key            TEXT NOT NULL,
    value_tiyn     BIGINT NOT NULL,
    value_units    BIGINT,
    effective_from DATE NOT NULL,
    effective_to   DATE,
    source_note    TEXT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
CREATE INDEX IF NOT EXISTS idx_tax_constants_lookup ON tax_constants (key, effective_from DESC);

