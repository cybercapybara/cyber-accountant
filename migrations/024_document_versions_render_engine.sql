-- Какой ДВИЖОК собрал PDF этой версии, например 'typst 0.15.1' или
-- 'xelatex'. Пишется рендер-джобой (src/docgen/RenderJob.hpp) в тот же
-- UPDATE, что и s3_key/checksum.
--
-- Зачем: Typst — pre-1.0, каждый минорный релиз несёт ломающие изменения
-- вёрстки. `template_version` отвечает на вопрос «каким ШАБЛОНОМ», но не на
-- вопрос «чем собрано»: один и тот же v1 под 0.15 и под 0.16 даёт разные
-- страницы. Документ — свидетельство, и через три года на аудите «повторите
-- этот расчётный лист» без версии движка не воспроизводится. Поэтому смена
-- движка или его версии трактуется как событие уровня v<N+1> шаблона.
--
-- Хранится РАЗОБРАННАЯ версия ('typst 0.15.1'), а не сырая строка
-- `typst --version` — та выглядит как `typst 0.15.1 (9dfd3a08)`, то есть
-- тащит за собой хеш коммита сборки и ломает любое сравнение на равенство.
-- Точная сборка при этом не теряется: тег версии + `TYPST_SHA256` в
-- docker/Dockerfile однозначно задают скачанный бинарник.
--
-- NOTE: MigrationRunner оборачивает файл в ОДНУ транзакцию. BEGIN/COMMIT
-- здесь не ставить.

ALTER TABLE document_versions ADD COLUMN IF NOT EXISTS render_engine TEXT;

-- Бэкфилл. NULL как «неизвестно» в проде был бы ложью: до этой миграции все
-- десять шаблонов собирались XeLaTeX'ом и другого движка в образе просто не
-- было (Typst появился в 7976ad5, первый typst-рендер — в 9f07a12, и обе
-- задачи ещё не выкатывались). Значит для КАЖДОЙ уже отрендеренной версии
-- ответ известен точно, и это 'xelatex'.
--
-- Условия сужают бэкфилл ровно до отрендеренных версий:
--   * d.source = 'generated' — файл загруженного (uploaded) или пришедшего
--     почтой (email) документа не производил НИКАКОЙ движок; проставить ему
--     'xelatex' значило бы выдумать провенанс. Такие версии остаются NULL, и
--     это правильное значение, а не пропуск: см. COALESCE в
--     DocumentRepository::set_version_file — путь confirm-upload не пишет
--     движок вообще;
--   * v.s3_key IS NOT NULL — версия без файла ещё не рендерилась; свой
--     движок она получит от джобы, когда та отработает;
--   * v.render_engine IS NULL — идемпотентность. Если журнал
--     schema_migrations потерян и набор 000..NNN проигрывается заново поверх
--     уже мигрированной схемы (сценарий, ради которого в 018 стоит
--     DO-гвард), typst-версия НЕ будет переписана на 'xelatex'.
--
-- Триггер updated_at выключается на время бэкфилла — ровно тот же довод, что
-- и в 018 для documents: заполнение новой колонки это переезд схемы, а не
-- правка версии, и оно не имеет права переставить время последнего изменения
-- у каждой существующей строки. Время правки версии — часть аудиторского
-- следа. ALTER TABLE ... DISABLE TRIGGER транзакционен и откатится вместе со
-- всем остальным при любой ошибке ниже.
ALTER TABLE document_versions DISABLE TRIGGER trg_document_versions_touch;

UPDATE document_versions v
   SET render_engine = 'xelatex'
  FROM documents d
 WHERE d.id = v.document_id
   AND d.org_id = v.org_id
   AND d.source = 'generated'
   AND v.s3_key IS NOT NULL
   AND v.render_engine IS NULL;

ALTER TABLE document_versions ENABLE TRIGGER trg_document_versions_touch;
