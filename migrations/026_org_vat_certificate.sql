-- Номер свидетельства о постановке на регистрационный учёт по НДС.
--
-- Отдельной миграцией, а не правкой 025: та уже в main, а миграции здесь
-- только вперёд (docs/RUNBOOK.md).
--
-- ЗАЧЕМ. `definitions.party` в templates/docs/tax_invoice/v1/schema.json —
-- единственная из десяти схем, где у стороны есть `vat_certificate`. Это
-- атрибут организации, а не документа: он один и тот же во всех её
-- счетах-фактурах. Пока его негде хранить, сервер не может заполнить
-- продавца полностью, и поле пришлось бы оставить клиентским — то есть
-- сохранить ровно ту дыру, которую закрывает 025.
ALTER TABLE organizations
    ADD COLUMN IF NOT EXISTS vat_certificate TEXT NOT NULL DEFAULT '';
