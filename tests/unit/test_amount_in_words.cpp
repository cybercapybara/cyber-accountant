// Казахские числительные. Источники (обращение 15.08.2026):
//
// [1] kk.wikipedia.org/wiki/Сан_есім — «Күрделі сан есім кемінде 2 сөзден
//     тұрады», пример ВЕРБАТИМ: «мың тоғыз жүз алпыс бес» (1965).
//     Подтверждает: единица перед «мың» опускается, «жүз» умножается
//     («тоғыз жүз»), разряд не получает окончаний.
// [2] el.kz/content-3357_2615 «Қазіргі қазақ тіліндегі сан есім» —
//     «Көбейту арқылы жүздік, мыңдық, миллион, миллиард сандардың аты
//     жасалады»: екі × жүз = екі жүз, бес × мың = бес мың, үш × миллион =
//     үш миллион. Пример ВЕРБАТИМ: «мың жүз елу» (1150) — подтверждает
//     ОБА опускания сразу, и перед «мың», и перед «жүз».
// [3] omniglot.com/language/numbers/kazakh.htm — сводная таблица:
//     нөл, бір, екі, үш, төрт, бес, алты, жеті, сегіз, тоғыз, он, жиырма,
//     отыз, қырық, елу, алпыс, жетпіс, сексен, тоқсан, жүз, екі жүз, мың.
// [4] informburo.kz/kaz/elaynasy/ailyq-tabysy-bir-million-tenge-... —
//     казахскоязычный текст: «Айлық табысы – бір миллион теңге»,
//     «Табысым орта есеппен айына 500 мың теңге». Подтверждает, что перед
//     «миллион» единица СОХРАНЯЕТСЯ, и что «теңге» после числительного не
//     получает окончания множественного числа.
//
// Расхождение с [3]: Omniglot печатает 1 000 000 как «миллион» без «бір» —
// это словарная лемма разряда, а не чтение числа; [4] показывает реальное
// чтение «бір миллион». Код следует [4].
//
// ОГРАНИЧЕНИЕ: нормативного двуязычного бланка с суммой прописью
// по-казахски найти не удалось — формат «<сумма> теңге NN тиын» взят из
// русской прописи задачи 1 и общей формы «___ теңге ____ тиын» госбланков.
// Казахский вывод считается ПРЕДВАРИТЕЛЬНЫМ до проверки носителем.
// ---------------------------------------------------------------------------

TEST(AmountInWordsKk, GoldenVectors) {
    const Vector kVectors[] = {
        {0, "Нөл теңге 00 тиын"},
        {1, "Нөл теңге 01 тиын"},
        {5, "Нөл теңге 05 тиын"},
        {67, "Нөл теңге 67 тиын"},
        {100, "Бір теңге 00 тиын"},
        {10000, "Жүз теңге 00 тиын"},       // единица ОПУЩЕНА перед жүз, [2][3]
        {100000, "Мың теңге 00 тиын"},      // единица ОПУЩЕНА перед мың, [1][2]
        {200000, "Екі мың теңге 00 тиын"},  // но двойка — нет, [2]
        {500000, "Бес мың теңге 00 тиын"},
        {1100000, "Он бір мың теңге 00 тиын"},      // 11 — два слова, не «одиннадцать»
        {2100000, "Жиырма бір мың теңге 00 тиын"},  // «бір» на конце триады остаётся
        {20000000, "Екі жүз мың теңге 00 тиын"},
        {11100000, "Жүз он бір мың теңге 00 тиын"},
        {25057500, "Екі жүз елу мың бес жүз жетпіс бес теңге 00 тиын"},
        {100000000, "Бір миллион теңге 00 тиын"},  // перед миллион единица НЕ опускается, [4]
        {1000000000, "Он миллион теңге 00 тиын"},
        {200200200, "Екі миллион екі мың екі теңге 00 тиын"},
        {100000000000, "Бір миллиард теңге 00 тиын"},
    };
    for (const auto& v : kVectors)
        EXPECT_EQ(Money::to_words_kk(v.tiyn), std::string(v.expected)) << "tiyn = " << v.tiyn;
}

// Две строки, взятые из источников ДОСЛОВНО, а не выведенные из правил, —
// единственная защита от того, чтобы реализация стала собственным оракулом.
TEST(AmountInWordsKk, VerbatimStringsFromSources) {
    EXPECT_EQ(Money::to_words_kk(196500), "Мың тоғыз жүз алпыс бес теңге 00 тиын");  // 1965 ₸, [1]
    EXPECT_EQ(Money::to_words_kk(115000), "Мың жүз елу теңге 00 тиын");              // 1150 ₸, [2]
}

// Единица опускается только как МНОЖИТЕЛЬ разряда. Внутри триады «бір»
// остаётся: 101 — «жүз бір», 1001 — «мың бір».
TEST(AmountInWordsKk, OneIsDroppedOnlyAsScaleMultiplier) {
    EXPECT_EQ(Money::to_words_kk(10100), "Жүз бір теңге 00 тиын");     // 101 ₸
    EXPECT_EQ(Money::to_words_kk(100100), "Мың бір теңге 00 тиын");    // 1001 ₸
    EXPECT_EQ(Money::to_words_kk(110000), "Мың жүз теңге 00 тиын");    // 1100 ₸
    EXPECT_EQ(Money::to_words_kk(10000000), "Жүз мың теңге 00 тиын");  // 100 000 ₸
}

TEST(AmountInWordsKk, CeilingAndSignMatchRussian) {
    EXPECT_EQ(Money::to_words_kk(Money::kMaxTiyn), "Бір триллион теңге 00 тиын");
    EXPECT_THROW(Money::to_words_kk(Money::kMaxTiyn + 1), std::out_of_range);
    EXPECT_THROW(Money::to_words_kk(-1), std::invalid_argument);
    EXPECT_THROW(Money::to_words_kk(-25057500), std::invalid_argument);
}

// Казахские буквы вне русского блока UTF-8: наивный capitalize их пропускал.
TEST(AmountInWordsKk, CapitalizesKazakhSpecificLetters) {
    EXPECT_EQ(Money::to_words_kk(300), "Үш теңге 00 тиын");      // ү (D2 AF) -> Ү (D2 AE)
    EXPECT_EQ(Money::to_words_kk(4000), "Қырық теңге 00 тиын");  // қ (D2 9B) -> Қ (D2 9A)
}

TEST(AmountInWordsKk, TiynAlwaysTwoDigits) {
    EXPECT_EQ(Money::to_words_kk(1207), "Он екі теңге 07 тиын");
    EXPECT_EQ(Money::to_words_kk(1299), "Он екі теңге 99 тиын");
}

// Пустая средняя триада не даёт слов: без этого получилось бы
// «екі миллион нөл мың».
TEST(AmountInWordsKk, EmptyMiddleTriadProducesNoWords) {
    EXPECT_EQ(Money::to_words_kk(200000000), "Екі миллион теңге 00 тиын");
    EXPECT_EQ(Money::to_words_kk(200000500), "Екі миллион бес теңге 00 тиын");
}

